import test from 'node:test';
import assert from 'node:assert/strict';
import { autoCredit, backfillDefault, balanceSave, blankExpense, blankIncome, blankPlanDraft, blankTopup, blankVirtual, canSwitchBilling, changeIncomeCategory, cleanTopup, endFields, expenseSave, paymentDraft, paymentSave, pastDues, planDraftFrom, planFieldsFromDraft, rangeCount, rangeDates, rangeSave, resumeDraft, skipSave, toggleRefund, validateEnd, validateExpense, validateIncome, validatePayment, validatePlanDraft, validateRange, validateResume, validateTopup, validateVirtual, virtualDraft, virtualSave } from '../src/mobile/spending/forms.ts';

const today = '2026-10-21';
test('支出：必填、退款联动、保存载荷带请求号与修订', () => {
  const f = blankExpense(today);
  assert.equal(validateExpense(f).message, '请填写名称。');
  assert.equal(validateExpense({ ...f, title: '旅行' }).message, '请填写金额。');
  const ok = { ...f, title: ' 旅行 ', amount_cents: '800000' };
  assert.equal(validateExpense(ok).ok, true);
  const on = toggleRefund(ok, true, today);
  assert.equal(on.refund_date, today);
  assert.equal(validateExpense(on).message, '请填写退款金额，或关闭退款。');
  assert.deepEqual([toggleRefund({ ...on, refund_cents: '100' }, false, today).refund_cents, toggleRefund({ ...on, refund_cents: '100' }, false, today).refund_date], [null, null]);
  const save = expenseSave(ok, { id: 'e1', revision: 3 }, 'g1', 'req');
  assert.deepEqual([save.request_id, save.generation, save.id, save.expected_revision, save.fields.title], ['req', 'g1', 'e1', 3, '旅行']);
  assert.equal(expenseSave(ok, null, 'g1', 'r').id, null);
});
test('计划草稿：简易表单读回、校验和过去期次补记默认', () => {
  const draft = { ...blankPlanDraft('2026-07-01'), name: '房租' };
  assert.equal(validatePlanDraft(draft, today).message, '请填写每期金额。');
  draft.rent.amount_cents = '450000';
  assert.equal(validatePlanDraft(draft, today).ok, true);
  assert.equal(pastDues(draft, today), 4);
  assert.equal(backfillDefault(draft), true);
  assert.equal(backfillDefault({ ...draft, category: 'subscription' }), false);
  assert.equal(backfillDefault({ ...draft, category: 'subscription', backfill: true }), true);
  draft.rent.end = '2026-06-01';
  assert.match(validatePlanDraft(draft, today).message, /到期日须晚于开始日期/);
  draft.rent.end = '2027-07-01';
  const fields = planFieldsFromDraft(null, draft, today);
  assert.equal(fields.end_date, '2027-06-30');
  assert.equal(fields.category, 'rent');
  const back = planDraftFrom({ id: 'p', revision: 1, fields, active_from: '2026-07-01', next_due: null });
  assert.equal(back.rent.end, '2027-07-01');
  assert.equal(planDraftFrom({ id: 'p', revision: 1, fields: { ...fields, interval_days: 10 }, active_from: '', next_due: null }), null);
});
test('结束计划：最后使用日不早于服务开始日，并关闭续费', () => {
  const f = planFieldsFromDraft(null, { ...blankPlanDraft('2026-07-01'), name: 'x', rent: { ...blankPlanDraft('2026-07-01').rent, amount_cents: '1' } }, today);
  assert.equal(validateEnd(f, '2026-06-01').ok, false);
  assert.equal(validateEnd(f, '').ok, false);
  assert.equal(validateEnd(f, '2026-12-31').ok, true);
  assert.deepEqual([endFields(f, '2026-12-31').end_date, endFields(f, '2026-12-31').auto_renew], ['2026-12-31', false]);
});
test('付款：已付要金额；跳过不带金额与日期；更正沿用修订', () => {
  const d = paymentDraft(null, '2026-10-01', '450000', today);
  assert.deepEqual([d.state, d.paid, d.amount], ['paid', '2026-10-01', '450000']);
  assert.equal(paymentDraft(null, '2026-11-01', '1', today).paid, today);
  assert.equal(validatePayment({ ...d, amount: '' }).message, '请填写实付金额。');
  assert.equal(validatePayment({ ...d, state: 'skipped', amount: '' }).ok, true);
  const record = { id: 'pay1', revision: 4, state: 'paid', paid_date: '2026-10-02', amount_cents: '440000', notes: 'n' };
  const save = paymentSave({ ...d, state: 'skipped' }, { plan_id: 'p1', due_date: '2026-10-01' }, record, 'g', 'r');
  assert.deepEqual([save.id, save.expected_revision, save.paid_date, save.amount_cents, save.state], ['pay1', 4, null, null, 'skipped']);
  assert.deepEqual([skipSave({ plan_id: 'p', due_date: 'd' }, 'g', 'r').state, skipSave({ plan_id: 'p', due_date: 'd' }, 'g', 'r').id], ['skipped', null]);
});
test('补记往期：需选中有效范围、金额并明确确认', () => {
  const plan = { id: 'p1', revision: 2, fields: planFieldsFromDraft(null, { ...blankPlanDraft('2026-07-01'), name: 'x', rent: { ...blankPlanDraft('2026-07-01').rent, amount_cents: '450000' } }, today), active_from: '', next_due: null };
  const dates = rangeDates(plan, today);
  assert.deepEqual(dates, ['2026-07-01', '2026-08-01', '2026-09-01', '2026-10-01']);
  const d = { from: dates[0], to: dates.at(-1), amount: '450000', confirmed: false };
  assert.equal(validateRange(dates, d).ok, false);
  assert.equal(validateRange(dates, { ...d, confirmed: true }).ok, true);
  assert.equal(rangeCount(dates, { ...d, from: '2026-09-01' }), 2);
  assert.equal(validateRange(dates, { ...d, confirmed: true, from: '2027-01-01', to: '2027-02-01' }).ok, false);
  const s = rangeSave(plan, { ...d, confirmed: true }, 'g', 'r');
  assert.deepEqual([s.plan_id, s.expected_revision, s.from_due, s.to_due, s.confirmed], ['p1', 2, '2026-07-01', '2026-10-01', true]);
});
test('重新订阅：生效日须晚于上段最后使用日', () => {
  const fields = { ...planFieldsFromDraft(null, { ...blankPlanDraft('2026-01-01'), category: 'subscription', name: 'x', rent: { ...blankPlanDraft('2026-01-01').rent, amount_cents: '3000' } }, today), end_date: '2026-06-30' };
  const plan = { id: 'p', revision: 5, fields, active_from: '', next_due: null };
  const d = resumeDraft(plan, null, today);
  assert.equal(d.start, today);
  assert.equal(validateResume(plan, null, d).ok, true);
  assert.equal(validateResume(plan, null, { ...d, start: '2026-06-30' }).ok, false);
  assert.equal(validateResume(plan, null, { ...d, amount: '' }).ok, false);
});
test('收入：分类切换、未知公积金与必填金额', () => {
  const f = blankIncome(today, '');
  assert.equal(f.hpf_cents, null);
  assert.equal(validateIncome(f, { original: null, depositConfirmed: false }).message, '请填写税后到账金额；没有到账就填 0。');
  assert.equal(validateIncome({ ...f, net_cents: '0' }, { original: null, depositConfirmed: false }).ok, true);
  const inv = changeIncomeCategory(blankIncome(today, '100000'), 'interest', true, false);
  assert.equal(inv.hpf_cents, null);
  assert.equal(inv.destination, 'unknown');
  const edited = changeIncomeCategory({ ...blankIncome(today, ''), hpf_cents: '5' }, 'interest', false, true);
  assert.equal(edited.hpf_cents, '5');
  assert.equal(validateIncome({ ...edited, net_cents: '1' }, { original: blankIncome(today, ''), depositConfirmed: false }).ok, false);
  assert.equal(validateIncome({ ...edited, net_cents: '1' }, { original: blankIncome(today, ''), depositConfirmed: true }).ok, true);
});
test('储值：到账额度默认实付加赠送；未知实付存 null，不落成 0', () => {
  assert.equal(autoCredit({ paid_cents: '1000', gift_cents: '200' }), '1200');
  assert.equal(autoCredit({ paid_cents: '', gift_cents: null }), null);
  const t = blankTopup(today);
  assert.equal(validateTopup(t, null).ok, false);
  assert.equal(validateTopup({ ...t, gift_cents: '100' }, '100').ok, true);
  const clean = cleanTopup({ ...t, paid_cents: '', gift_cents: '100' }, '100');
  assert.deepEqual([clean.paid_cents, clean.credit_cents], [null, '100']);
  const b = balanceSave({ cents: '5000', date: today, notes: '' }, { id: 'v', balance: { id: 'b', revision: 2 } }, 'g', 'r');
  assert.deepEqual([b.id, b.expected_revision, b.balance_cents, b.recorded_on], ['b', 2, '5000', today]);
});
test('虚拟资产：储值可带首次充值；买断不携带计划；不能换计费方式', () => {
  const d = virtualDraft(null, today);
  d.fields = { ...d.fields, name: 'Notion' };
  d.plan.rent.amount_cents = '9000';
  const sub = virtualSave(null, d, 'g', today, 'r');
  assert.ok(sub.plan && sub.plan.fields.amount_cents === '9000');
  assert.equal(sub.plan.fields.category, 'subscription');
  assert.equal(sub.fields.expires, null);
  const topup = virtualDraft(null, today);
  topup.fields = { ...topup.fields, name: '咖啡卡', billing: 'topup' };
  topup.withTopup = true; topup.firstTopup = { ...topup.firstTopup, paid_cents: '10000', gift_cents: '1000' };
  const save = virtualSave(null, topup, 'g', today, 'r');
  assert.equal(save.plan, undefined);
  assert.equal(save.first_topup.credit_cents, '11000');
  const single = virtualDraft(null, today);
  single.fields = { ...single.fields, name: '软件', billing: 'single' };
  assert.equal(virtualSave(null, single, 'g', today, 'r').plan, undefined);
  assert.equal(validateVirtual(null, { ...single, perpetual: true, fields: { ...single.fields, expires: '2030-01-01' } }, today).ok, false);
  assert.equal(validateVirtual(null, { ...single, fields: { ...single.fields, name: '' } }, today).message, '请填写名称。');
  const existing = { id: 'v', revision: 2, fields: { ...blankVirtual(), name: 'x', billing: 'topup' }, topup_count: 2 };
  assert.equal(canSwitchBilling(existing, 'single').ok, false);
  assert.equal(canSwitchBilling(existing, 'topup').ok, true);
  assert.equal(canSwitchBilling({ ...existing, topup_count: 0 }, 'single').ok, true);
});
