// Reproducible, project-owned vector icons. Existing eight PNGs stay intact.
import { createRequire } from 'node:module';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { MATERIALS, materialArt } from '../src/materials.ts';
const sharp = createRequire(import.meta.url)(process.argv[2] || 'sharp');
for (const m of MATERIALS.filter(m => m.id.startsWith('icon-') || m.id.startsWith('object3d-'))) {
  await sharp(Buffer.from(materialArt(m.id))).resize(320,320).png().toFile(fileURLToPath(new URL(`../src-tauri/materials/${m.id}.png`, import.meta.url)));
}
const arms = MATERIALS.map(m => `        ${JSON.stringify(m.id)} => include_bytes!("../materials/${m.id}.png"),`).join('\n');
await writeFile(new URL('../src-tauri/src/material_artwork.rs', import.meta.url), `// Generated by scripts/render-material-icons.mjs from the material catalog.\nfn artwork(id: &str) -> Option<&'static [u8]> {\n    Some(match id {\n${arms}\n        _ => return None,\n    })\n}\n`);
console.log(`Rendered ${MATERIALS.filter(m=>m.style==='icon').length} icons; catalog contains ${MATERIALS.length} materials.`);
