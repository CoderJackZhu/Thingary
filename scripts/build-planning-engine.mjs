import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const crate = join(root, 'crates/planning-engine');
const target = join(root, 'src-tauri/target/planning-engine');
const collect = (dir) => readdirSync(dir, { withFileTypes: true }).flatMap(entry =>
  entry.isDirectory() ? collect(join(dir, entry.name)) : [join(dir, entry.name)]);
// Hash repository-relative names in one format on macOS and Windows.
const inputs = [join(crate, 'Cargo.toml'), join(crate, 'Cargo.lock'), ...collect(join(crate, 'src'))]
  .map(path => ({ path, name: relative(crate, path).replaceAll('\\', '/') }))
  .sort((a, b) => a.name < b.name ? -1 : a.name > b.name ? 1 : 0);
const hash = createHash('sha256');
for (const { path, name } of inputs) hash.update(name).update('\0').update(readFileSync(path)).update('\0');
const sourceHash = hash.digest('hex');
const destination = join(root, 'src/planning-engine-wasm.ts');
if (process.argv.includes('--check-source')) {
  const packaged = readFileSync(destination, 'utf8');
  const field = name => packaged.match(new RegExp(`^export const ${name} = '([^']+)';$`, 'm'))?.[1];
  if (field('planningEngineSourceHash') !== sourceHash) throw new Error('Committed WASM has stale Rust inputs. Run npm run build:engine.');
  const encoded = field('planningEngineWasm');
  if (!encoded || !/^[A-Za-z0-9+/]+={0,2}$/.test(encoded)) throw new Error('Invalid packaged WASM encoding.');
  const packagedBytes = Buffer.from(encoded, 'base64');
  if (createHash('sha256').update(packagedBytes).digest('hex') !== field('planningEngineWasmHash')) throw new Error('Packaged WASM binary hash differs.');
  verifyModule(packagedBytes);
  console.log(`Packaged planning engine matches Rust inputs ${sourceHash.slice(0, 12)}`);
} else if (!process.argv.includes('--check') && !process.argv.includes('--force') && isCurrent()) {
  // The committed artifact is the reviewed one: rebuilding it on another Rust toolchain changes bytes without changing the inputs.
  console.log(`Planning engine up to date for Rust inputs ${sourceHash.slice(0, 12)}; pass --force to rebuild.`);
} else {
  execFileSync('cargo', ['build', '--locked', '--release', '--target', 'wasm32-unknown-unknown',
    '--target-dir', target, '--manifest-path', join(crate, 'Cargo.toml')], { cwd: root, stdio: 'inherit' });
  const bytes = readFileSync(join(target, 'wasm32-unknown-unknown/release/thingary_planning_engine.wasm'));
  verifyModule(bytes);
  const output = `// Generated by scripts/build-planning-engine.mjs from the Rust crate. Do not edit.\n` +
    `export const planningEngineSourceHash = '${sourceHash}';\n` +
    `export const planningEngineWasmHash = '${createHash('sha256').update(bytes).digest('hex')}';\n` +
    `export const planningEngineWasm = '${bytes.toString('base64')}';\n`;
  if (process.argv.includes('--check')) {
    if (readFileSync(destination, 'utf8') !== output) throw new Error('Rust source and packaged WASM differ. Run npm run build:engine.');
  } else {
    writeFileSync(destination, output);
  }
  console.log(`Planning engine: ${bytes.length} bytes, source ${sourceHash.slice(0, 12)}`);
}

function isCurrent() {
  try {
    const packaged = readFileSync(destination, 'utf8');
    const field = name => packaged.match(new RegExp(`^export const ${name} = '([^']+)';$`, 'm'))?.[1];
    const encoded = field('planningEngineWasm');
    if (field('planningEngineSourceHash') !== sourceHash || !encoded) return false;
    const bytes = Buffer.from(encoded, 'base64');
    if (createHash('sha256').update(bytes).digest('hex') !== field('planningEngineWasmHash')) return false;
    verifyModule(bytes);
    return true;
  } catch { return false; }
}

function verifyModule(bytes) {
  const module = new WebAssembly.Module(bytes);
  if (WebAssembly.Module.imports(module).length) throw new Error('Planning WASM must not import host capabilities.');
  for (const name of ['memory', 'alloc', 'release', 'evaluate', 'result_len']) {
    if (!WebAssembly.Module.exports(module).some(item => item.name === name)) throw new Error(`Missing WASM export: ${name}`);
  }
}
