// Maintainer tool: refreshes src/reference-rates.ts from the ECB euro foreign exchange reference rates (via api.frankfurter.dev).
// The app itself never goes online for this: the snapshot ships with each release and is only a default estimate.
// Pegged currencies are derived from their fixed peg; currencies the ECB does not publish stay out (the user types those once).
import fs from 'node:fs';
const res = await fetch('https://api.frankfurter.dev/v1/latest?base=EUR');
if (!res.ok) throw new Error(`HTTP ${res.status}`);
const { date, rates } = await res.json();
const perEur = { EUR: 1, ...rates };
const cnyPerEur = perEur.CNY;
const cnyPer = code => cnyPerEur / perEur[code]; // CNY for 1 unit of `code`
const out = {};
for (const code of ['USD', 'JPY', 'EUR', 'GBP', 'KRW', 'HKD', 'SGD', 'AUD', 'CAD', 'CHF', 'NZD', 'THB', 'MYR', 'IDR', 'PHP', 'INR', 'TRY', 'BRL', 'MXN', 'ZAR', 'SEK', 'NOK', 'DKK', 'PLN', 'CZK', 'HUF', 'ILS']) if (perEur[code]) out[code] = cnyPer(code);
// Fixed pegs: 1 USD = 3.6725 AED, 1 USD = 3.75 SAR, 1.03 MOP = 1 HKD.
out.AED = out.USD / 3.6725; out.SAR = out.USD / 3.75; out.MOP = out.HKD / 1.03;
const micro = Object.fromEntries(Object.entries(out).sort(([a], [b]) => a.localeCompare(b)).map(([c, v]) => [c, Math.round(v * 1e6).toString()]));
const body = `// Generated by scripts/update-reference-rates.mjs — do not edit by hand.
// ECB euro reference rates of ${date}, converted to CNY per 1 unit (micro units, i.e. 1e-6 CNY). A default estimate only, never a fact.
export const referenceRatesDate = '${date}';
export const referenceRates: Record<string, string> = ${JSON.stringify(micro, null, 2).replace(/"([A-Z]{3})":/g, '$1:').replace(/"/g, "'")};
`;
fs.writeFileSync(new URL('../src/reference-rates.ts', import.meta.url), body);
console.log(`wrote ${Object.keys(micro).length} rates for ${date}`);
